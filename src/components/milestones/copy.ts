/** Short boss names for tight spaces (tree labels, speech bubbles, buttons). */
export const BOSS_SHORT_NAMES: Record<BossKey, { en: string; ar: string }> = {
  number_giant: { en: "Numbo", ar: "نُمبو" },
  word_dragon: { en: "Wordy", ar: "وردي" },
  letter_camel: { en: "Harfi", ar: "حَرفي" },
  sprout_buddy: { en: "Sprouty", ar: "بُرعم" },
  puzzle_owlet: { en: "Puzzle Owlet", ar: "البومة الصغيرة" },
  letter_dragon: { en: "Harf", ar: "حَرف" },
};

export function bossName(bossKey: BossKey, lang: Lang, short = false): string {
  return (short ? BOSS_SHORT_NAMES : BOSS_NAMES)[bossKey][lang];
}

/** Numbers in the Arabic UI use ar-EG digits, as the emails do. */
export function formatNumber(value: number, lang: Lang): string {
  return new Intl.NumberFormat(lang === "ar" ? "ar-EG" : "en-GB").format(value);
}

export function formatDate(iso: string, lang: Lang): string {
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return "";
  return new Intl.DateTimeFormat(lang === "ar" ? "ar-EG" : "en-GB", {
    day: "numeric",
    month: "long",
    year: "numeric",
  }).format(date);
}

/** Speak a short line with the phone's own voice (boss taunts, fallbacks). */
export function speakLine(text: string, lang: Lang): boolean {
  if (typeof window === "undefined" || !("speechSynthesis" in window) || !text) return false;
  const utterance = new SpeechSynthesisUtterance(text);
  utterance.lang = lang === "ar" ? "ar-SA" : "en-GB";
  utterance.rate = 0.9;
  window.speechSynthesis.cancel();
  window.speechSynthesis.speak(utterance);
  return true;
}
